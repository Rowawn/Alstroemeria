#!/usr/bin/env node
// Generate THIRD-PARTY-NOTICES.md (SPEC §17.6): Rust crates through `cargo about`, the npm packages that ship in
// the UI bundle, and the data licences. About imports the file (a lazy chunk) so every bundle carries it. Needs `cargo install cargo-about`.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");

const rust = execFileSync("cargo", ["about", "generate", "--workspace", "about.hbs"], { cwd: root, encoding: "utf8", maxBuffer: 64 << 20 });

// npm packages whose code ends up in the UI bundle (the runtime parts of the dev toolchain are MIT too).
const shipped = ["@tauri-apps/api", "@tauri-apps/plugin-barcode-scanner", "svelte", "@sveltejs/kit"];
let npm = "## npm packages in the UI\n\n";
for (const name of shipped) {
  const dir = join(root, "node_modules", name);
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const file = ["LICENSE", "LICENSE.md", "LICENSE-MIT", "LICENSE.txt"].map((f) => join(dir, f)).find(existsSync);
  npm += `### ${name} ${pkg.version} (${pkg.license})\n\n${file ? "```\n" + readFileSync(file, "utf8").trim() + "\n```\n" : "See " + (pkg.repository?.url ?? "its repository") + "\n"}\n`;
}

const data = `## Language data and extension data

- **mecab-ipadic-2.7.0** (Japanese dictionary, downloaded as language data): Copyright 2000-2007 Nara Institute of
  Science and Technology (NAIST) and ICOT Free Software. Its full notice ships inside the language data package
  (\`LICENSE.txt\`) and is reproduced by the Lindera project: https://github.com/lindera/lindera
- **mecab-ko-dic-2.1.1** (Korean dictionary, downloaded as language data): Apache-2.0, Copyright Eunjeon project.
- **libhangul hanja data** (Korean hanja add-on): BSD-3-Clause, see \`extensions/ko-hanja/DATA-LICENSE\`:

\`\`\`
${read("extensions/ko-hanja/DATA-LICENSE").trim()}
\`\`\`
`;

const out = `# Third-party notices

Alstroemeria itself is MPL-2.0 (core) and MIT (extensions and SDK). It includes the software and data listed below.
This file is generated by \`scripts/gen-notices.mjs\`.

${data}
${npm}
${rust}`;
writeFileSync(join(root, "THIRD-PARTY-NOTICES.md"), out);
console.log(`THIRD-PARTY-NOTICES.md: ${(out.length / 1024).toFixed(0)} KB`);
